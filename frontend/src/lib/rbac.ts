export const ROLE_DISCOUNT_CEILING: Record<UserRoleCode, number> = {
  OWNER: 100,
  MANAGER: 20,
  CASHIER: 5,
  CHEF: 0,
  WAITER: 0,
  STAFF: 0,
};

export function getPermissionsForRole(role?: string | null): readonly PermissionCode[] {
  if (!role) return [];
  const normalized = role.toUpperCase() as UserRoleCode;
  return ROLE_PERMISSIONS[normalized] ?? [];
}

export function getDiscountCeiling(role?: string | null): number {
  if (!role) return 0;
  const normalized = role.toUpperCase() as UserRoleCode;
  return ROLE_DISCOUNT_CEILING[normalized] ?? 0;
}

export function hasPermission(
  role: string | null | undefined,
  permission: PermissionCode,
  explicitPermissions?: readonly string[],
): boolean {
  if (explicitPermissions && explicitPermissions.length > 0) {
    return explicitPermissions.includes(permission);
  }
  return getPermissionsForRole(role).includes(permission);
}

export function hasAnyPermission(
  role: string | null | undefined,
  permissions: readonly PermissionCode[],
  explicitPermissions?: readonly string[],
): boolean {
  return permissions.some((p) => hasPermission(role, p, explicitPermissions));
}

