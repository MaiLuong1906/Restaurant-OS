const PUBLIC_PREFIXES = [
  '/login',
  '/kds/login',
  '/qr',
  '/menu',
  '/cart',
  '/orders',
  '/checkout',
  '/payment-success',
];

export function canAccessRoute(
  pathname: string,
  role?: string | null,
  isKdsAuthenticated = false,
  explicitPermissions?: readonly string[],
): boolean {
  // Public routes (Login, KDS Login, Customer QR) — khớp chính xác segment để tránh /menu-bom khớp nhầm /menu
  if (
    pathname === '/' ||
    PUBLIC_PREFIXES.some((p) => pathname === p || pathname.startsWith(`${p}/`))
  ) {
    return true;
  }

  const rule = ROUTE_REQUIRED_PERMISSIONS.find(
    (r) => pathname === r.prefix || pathname.startsWith(`${r.prefix}/`),
  );
  if (!rule) {
    return true;
  }

  if (rule.allowKds && isKdsAuthenticated) {
    return true;
  }

  return hasAnyPermission(role, rule.anyOf, explicitPermissions);
}
